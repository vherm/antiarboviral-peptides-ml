from seed_utils import set_global_seed


ALL_ALGORITHMS = ["SVM", "RF", "KNN", "NB", "MLP", "XGBoost"]
ALL_FEATURE_SELECTION_METHODS = [
    "none",
    "prefilter",
    "percentile",
    "percentile_chi2",
    "rfe",
    "rfecv",
    "sfm_l1",
    "sfm_rf",
    "sfm_xgb",
]
ALL_REPRESENTATIONS = ["ESM-2", "iLearn"]
ALL_PERMUTATION_SCORING = ["average_precision", "mcc", "f1"]


def sanitize_filename_component(value: str) -> str:
    """Return a filesystem-safe text component for output filenames."""
    safe_chars = []
    for character in value:
        if character.isalnum() or character in {"-", "_", "."}:
            safe_chars.append(character)
        else:
            safe_chars.append("_")
    return "".join(safe_chars).strip("_") or "dataset"


def build_summary_filename(dataset_label: str) -> str:
    """Build the summary filename using the dataset label."""
    safe_dataset_label = sanitize_filename_component(dataset_label)
    return f"{safe_dataset_label}_model_summary.xlsx"


def validate_input_files(train_file: str, test_file: str) -> tuple[Path, Path]:
    """Validate that both train and test CSV files were provided and exist."""
    if not train_file or not test_file:
        raise ValueError("Both --train_file and --test_file are required.")

    train_path = Path(train_file)
    test_path = Path(test_file)

    if not train_path.is_file():
        raise FileNotFoundError(f"Training file not found: {train_path}")

    if not test_path.is_file():
        raise FileNotFoundError(f"Test file not found: {test_path}")

    return train_path, test_path


def parse_comma_separated_values(
    value: str,
    allowed_values: list[str],
    option_name: str,
) -> list[str]:
    """Parse a comma-separated command-line option or expand 'all'."""
    if value.lower() == "all":
        return allowed_values

    selected_values = [
        item.strip()
        for item in value.split(",")
        if item.strip()
    ]
    invalid_values = [
        item
        for item in selected_values
        if item not in allowed_values
    ]

    if invalid_values:
        raise ValueError(
            f"Invalid value(s) for {option_name}: {invalid_values}. "
            f"Allowed values are: {allowed_values}, or 'all'."
        )

    if not selected_values:
        raise ValueError(f"No valid values were provided for {option_name}.")

    return selected_values


def build_expected_artifact_names(
    algorithm: str,
    feature_selection_method: str,
    top_features: int,
) -> list[str]:
    """
    Return artifact filenames potentially generated by main.py.

    Some interpretability artifacts are model/representation dependent. It is
    safe to include all potential names because move_generated_artifacts() only
    moves files that actually exist.
    """
    prefix = f"{algorithm}_{feature_selection_method}"

    return [
        f"{prefix}_model_report.xlsx",
        f"{prefix}_model_report.pdf",
        f"{prefix}_confusion_matrix.png",
        f"{prefix}_roc_curve.png",
        f"{prefix}_log.txt",
        f"{prefix}_best_parameters.json",
        f"{prefix}_selected_features.csv",
        f"{prefix}_selected_feature_names.txt",
        f"{prefix}_precision_recall_curve.png",
        f"{prefix}_precision_recall_curve.csv",
        f"{prefix}_predictions.csv".replace(" ", "_"),
        f"{prefix}_features_count.txt".replace(" ", "_"),
        # Individual permutation importance
        f"{prefix}_permutation_importance.csv",
        f"{prefix}_top{top_features}_permutation_importance.csv",
        f"{prefix}_top{top_features}_permutation_importance.png",
        # Grouped iLearn permutation importance
        f"{prefix}_family_permutation_importance.csv",
        f"{prefix}_family_permutation_importance.png",
        # SHAP
        f"{prefix}_shap_importance.csv",
        f"{prefix}_top{top_features}_shap_importance.csv",
        f"{prefix}_top{top_features}_shap_importance.png",
        # Grouped iLearn SHAP
        f"{prefix}_shap_family_importance.csv",
        f"{prefix}_shap_family_importance.png",
        # Interpretability audit metadata
        f"{prefix}_interpretability_metadata.json",
    ]


def move_generated_artifacts(
    artifact_names: list[str],
    destination_dir: Path,
    working_dir: Path,
) -> None:
    """Move generated artifacts from the working directory to the destination directory."""
    destination_dir.mkdir(parents=True, exist_ok=True)

    for artifact_name in artifact_names:
        source_path = working_dir / artifact_name
        destination_path = destination_dir / artifact_name

        if source_path.exists():
            try:
                shutil.move(str(source_path), str(destination_path))
            except Exception as error:
                print(f"[WARN] Could not move {source_path}: {error}")


def read_best_parameters(json_path: Path) -> str:
    """Read the best-parameters JSON file and return it as a compact string."""
    if not json_path.exists():
        return ""

    with open(json_path, "r", encoding="utf-8") as file:
        json_data = json.load(file)

    return json.dumps(json_data, ensure_ascii=False)


def append_metrics_summary(
    summary_rows: list[dict],
    report_path: Path,
    best_parameters_path: Path,
    dataset_label: str,
    algorithm: str,
    feature_selection_method: str,
    representation: str,
) -> None:
    """Append one model-report row to the global experiment summary."""
    if not report_path.exists():
        print(f"[WARN] Report file not found: {report_path}")
        return

    metrics_df = pd.read_excel(report_path, index_col=0)
    report_column_name = metrics_df.columns[0]
    metrics = metrics_df[report_column_name].to_dict()

    # Metadata are added explicitly below, so remove any copies read from the
    # individual report.
    metrics.pop("Dataset", None)
    metrics.pop("CSV file", None)
    metrics.pop("Algorithm", None)
    metrics.pop("Feature selection method", None)

    best_parameters = read_best_parameters(best_parameters_path)

    summary_rows.append(
        {
            "CSV file": dataset_label,
            "Representation": representation,
            "Algorithm": algorithm,
            "Feature selection method": feature_selection_method,
            **metrics,
            "Best parameters": best_parameters,
        }
    )


def run_single_experiment(
    main_script: Path,
    train_path: Path,
    test_path: Path,
    algorithm: str,
    feature_selection_method: str,
    search_mode: str,
    cv_folds: int,
    working_dir: Path,
    representation: str,
    interpretability: str,
    top_features: int,
    permutation_repeats: int,
    permutation_scoring: str,
) -> None:
    """Run main.py for one algorithm and one feature selection method."""
    command = [
        sys.executable,
        str(main_script),
        "--algorithm",
        algorithm,
        "--feature_selection_method",
        feature_selection_method,
        "--search_mode",
        search_mode,
        "--cv",
        str(cv_folds),
        "--train_file",
        str(train_path),
        "--test_file",
        str(test_path),
        "--representation",
        representation,
        "--interpretability",
        interpretability,
        "--top_features",
        str(top_features),
        "--permutation_repeats",
        str(permutation_repeats),
        "--permutation_scoring",
        permutation_scoring,
    ]

    subprocess.run(command, check=True, cwd=working_dir)


def format_elapsed_time(seconds: float) -> str:
    """Format elapsed seconds as HH:MM:SS."""
    total_seconds = int(round(seconds))
    hours, remainder = divmod(total_seconds, 3600)
    minutes, remaining_seconds = divmod(remainder, 60)
    return f"{hours:02d}:{minutes:02d}:{remaining_seconds:02d}"


def write_timing_report(
    output_file: Path,
    dataset_label: str,
    representation: str,
    combination_timings: list[dict],
    model_timings: dict[str, float],
    total_elapsed_seconds: float,
) -> None:
    """Write cumulative execution times to a text file."""
    output_file.parent.mkdir(parents=True, exist_ok=True)

    completed_counts = {}
    for record in combination_timings:
        algorithm = record["algorithm"]
        completed_counts[algorithm] = completed_counts.get(algorithm, 0) + 1

    lines = [
        "ML PIPELINE TIMING REPORT",
        "=" * 80,
        f"Dataset: {dataset_label}",
        f"Representation: {representation}",
        (
            "Total elapsed time: "
            f"{format_elapsed_time(total_elapsed_seconds)} "
            f"({total_elapsed_seconds:.2f} seconds)"
        ),
        "",
        "1. TOTAL TIME BY MODEL",
        "-" * 80,
    ]

    for algorithm, elapsed_seconds in model_timings.items():
        experiment_count = completed_counts.get(algorithm, 0)
        lines.append(
            f"{algorithm}: {format_elapsed_time(elapsed_seconds)} "
            f"({elapsed_seconds:.2f} seconds; "
            f"{experiment_count} feature-selection experiment(s))"
        )

    lines.extend(
        [
            "",
            "2. TIME BY MODEL + FEATURE-SELECTION METHOD",
            "-" * 80,
        ]
    )

    for record in combination_timings:
        lines.append(
            f"{record['algorithm']} + {record['feature_selection_method']}: "
            f"{format_elapsed_time(record['elapsed_seconds'])} "
            f"({record['elapsed_seconds']:.2f} seconds; "
            f"status={record['status']})"
        )

    lines.append("")
    output_file.write_text("\n".join(lines), encoding="utf-8")


def run_experiments(args: argparse.Namespace) -> None:
    """Run all requested model experiments using a predefined train/test split."""
    set_global_seed()

    start_time = time.time()
    working_dir = Path.cwd()
    script_dir = Path(__file__).resolve().parent
    main_script = script_dir / "main.py"

    if not main_script.is_file():
        raise FileNotFoundError(
            f"main.py was not found next to this launcher: {main_script}"
        )

    train_path, test_path = validate_input_files(
        args.train_file,
        args.test_file,
    )
    results_dir = Path(args.results_dir)
    results_dir.mkdir(parents=True, exist_ok=True)

    algorithms = parse_comma_separated_values(
        args.algorithms,
        ALL_ALGORITHMS,
        "--algorithms",
    )
    feature_selection_methods = parse_comma_separated_values(
        args.feature_selection_methods,
        ALL_FEATURE_SELECTION_METHODS,
        "--feature_selection_methods",
    )

    dataset_label = f"{train_path.stem}__{test_path.stem}"
    summary_rows = []

    timing_file = results_dir / "time.txt"
    combination_timings = []
    model_timings = {algorithm: 0.0 for algorithm in algorithms}

    print(f"[INFO] Training file: {train_path}")
    print(f"[INFO] Test file: {test_path}")
    print(f"[INFO] Representation: {args.representation}")
    print(f"[INFO] Algorithms: {algorithms}")
    print(f"[INFO] Feature selection methods: {feature_selection_methods}")
    print(f"[INFO] Interpretability mode: {args.interpretability}")
    print(f"[INFO] Top features: {args.top_features}")
    print(f"[INFO] Permutation repeats: {args.permutation_repeats}")
    print(f"[INFO] Permutation scoring: {args.permutation_scoring}")

    for algorithm in algorithms:
        for feature_selection_method in feature_selection_methods:
            print(
                f"\n[RUN] {dataset_label} | {args.representation} | "
                f"{algorithm} | FS={feature_selection_method}"
            )

            combination_start_time = time.perf_counter()

            try:
                run_single_experiment(
                    main_script=main_script,
                    train_path=train_path,
                    test_path=test_path,
                    algorithm=algorithm,
                    feature_selection_method=feature_selection_method,
                    search_mode=args.search_mode,
                    cv_folds=args.cv,
                    working_dir=working_dir,
                    representation=args.representation,
                    interpretability=args.interpretability,
                    top_features=args.top_features,
                    permutation_repeats=args.permutation_repeats,
                    permutation_scoring=args.permutation_scoring,
                )
            except subprocess.CalledProcessError as error:
                print(
                    f"[ERROR] Experiment failed: {dataset_label} | "
                    f"{algorithm} | FS={feature_selection_method}"
                )
                print(f"[ERROR] Details: {error}")

                elapsed_seconds = (
                    time.perf_counter() - combination_start_time
                )
                combination_timings.append(
                    {
                        "algorithm": algorithm,
                        "feature_selection_method": feature_selection_method,
                        "elapsed_seconds": elapsed_seconds,
                        "status": "FAILED",
                    }
                )
                model_timings[algorithm] += elapsed_seconds

                write_timing_report(
                    output_file=timing_file,
                    dataset_label=dataset_label,
                    representation=args.representation,
                    combination_timings=combination_timings,
                    model_timings=model_timings,
                    total_elapsed_seconds=time.time() - start_time,
                )

                print(
                    f"[TIME] {algorithm} + {feature_selection_method}: "
                    f"{format_elapsed_time(elapsed_seconds)} "
                    f"({elapsed_seconds:.2f} seconds; status=FAILED)",
                    flush=True,
                )
                print(
                    f"[TIME] Timing report updated: {timing_file}",
                    flush=True,
                )
                continue

            experiment_dir = (
                results_dir
                / dataset_label
                / algorithm
                / feature_selection_method
            )
            artifact_names = build_expected_artifact_names(
                algorithm,
                feature_selection_method,
                args.top_features,
            )
            move_generated_artifacts(
                artifact_names=artifact_names,
                destination_dir=experiment_dir,
                working_dir=working_dir,
            )

            report_path = (
                experiment_dir
                / f"{algorithm}_{feature_selection_method}_model_report.xlsx"
            )
            best_parameters_path = (
                experiment_dir
                / f"{algorithm}_{feature_selection_method}_best_parameters.json"
            )

            append_metrics_summary(
                summary_rows=summary_rows,
                report_path=report_path,
                best_parameters_path=best_parameters_path,
                dataset_label=dataset_label,
                algorithm=algorithm,
                feature_selection_method=feature_selection_method,
                representation=args.representation,
            )

            elapsed_seconds = time.perf_counter() - combination_start_time
            combination_timings.append(
                {
                    "algorithm": algorithm,
                    "feature_selection_method": feature_selection_method,
                    "elapsed_seconds": elapsed_seconds,
                    "status": "COMPLETED",
                }
            )
            model_timings[algorithm] += elapsed_seconds

            write_timing_report(
                output_file=timing_file,
                dataset_label=dataset_label,
                representation=args.representation,
                combination_timings=combination_timings,
                model_timings=model_timings,
                total_elapsed_seconds=time.time() - start_time,
            )

            print(
                f"[TIME] {algorithm} + {feature_selection_method}: "
                f"{format_elapsed_time(elapsed_seconds)} "
                f"({elapsed_seconds:.2f} seconds; status=COMPLETED)",
                flush=True,
            )
            print(
                f"[TIME] Timing report updated: {timing_file}",
                flush=True,
            )

    if summary_rows:
        summary_df = pd.DataFrame(summary_rows)
        summary_filename = build_summary_filename(dataset_label)
        summary_path = results_dir / summary_filename
        summary_df.to_excel(summary_path, index=False)
        print(f"\n[OK] Summary file saved to: {summary_path}")
    else:
        print(
            "\n[WARN] No summary was generated. Please check whether model "
            "reports were created."
        )

    end_time = time.time()
    elapsed_time = end_time - start_time

    write_timing_report(
        output_file=timing_file,
        dataset_label=dataset_label,
        representation=args.representation,
        combination_timings=combination_timings,
        model_timings=model_timings,
        total_elapsed_seconds=elapsed_time,
    )

    print(f"Start time: {start_time}")
    print(f"End time: {end_time}")
    print(f"Elapsed time: {elapsed_time:.2f} seconds")
    print("\n[OK] Finished.")


def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Run automatic ML experiments using predefined training and test "
            "CSV files. The expected CSV format is: #, sequence, label, features..."
        )
    )

    parser.add_argument(
        "--train_file",
        required=True,
        help="Training CSV file.",
    )
    parser.add_argument(
        "--test_file",
        required=True,
        help="Test CSV file.",
    )
    parser.add_argument(
        "--representation",
        required=True,
        choices=ALL_REPRESENTATIONS,
        help=(
            "Descriptor representation used by the input files: ESM-2 or iLearn."
        ),
    )
    parser.add_argument(
        "--algorithms",
        default="SVM,RF,XGBoost,NB",
        help=(
            "Comma-separated algorithms or 'all'. "
            "Allowed values: SVM, RF, KNN, NB, MLP, XGBoost."
        ),
    )
    parser.add_argument(
        "--feature_selection_methods",
        default="all",
        help=(
            "Comma-separated feature selection methods or 'all'. "
            "Allowed values: none, prefilter, percentile, percentile_chi2, "
            "rfe, rfecv, sfm_l1, sfm_rf, sfm_xgb."
        ),
    )
    parser.add_argument(
        "--search_mode",
        default="grid",
        choices=["grid", "random"],
        help="Hyperparameter search mode. Default: grid.",
    )
    parser.add_argument(
        "--cv",
        type=int,
        default=5,
        help="Number of cross-validation folds. Default: 5.",
    )
    parser.add_argument(
        "--interpretability",
        default="none",
        choices=["none", "permutation", "shap", "all"],
        help=(
            "Interpretability analysis to run: none, permutation, shap, or all. "
            "Default: none."
        ),
    )
    parser.add_argument(
        "--top_features",
        type=int,
        default=20,
        help="Number of top features to export and plot. Default: 20.",
    )
    parser.add_argument(
        "--permutation_repeats",
        type=int,
        default=10,
        help="Number of repeats for permutation importance. Default: 10.",
    )
    parser.add_argument(
        "--permutation_scoring",
        default="average_precision",
        choices=ALL_PERMUTATION_SCORING,
        help=(
            "Metric used for permutation importance. Default for Round 4A: "
            "average_precision. This does not change the F1-based "
            "GridSearchCV used in Round 2."
        ),
    )
    parser.add_argument(
        "--results_dir",
        default="results",
        help=(
            "Directory where experiment outputs will be stored. Default: results."
        ),
    )

    return parser.parse_args()


def main() -> None:
    args = parse_arguments()
    run_experiments(args)


if __name__ == "__main__":
    main()
