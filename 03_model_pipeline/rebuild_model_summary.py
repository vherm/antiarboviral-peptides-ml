import argparse
import json
from pathlib import Path
from typing import Any

import pandas as pd


DEFAULT_RESULTS_DIR = "results"
DEFAULT_OUTPUT_FILE = None

KNOWN_ALGORITHMS = ["SVM", "RF", "KNN", "NB", "MLP", "XGBoost"]
KNOWN_FEATURE_SELECTION_METHODS = [
    "none",
    "prefilter",
    "kbest",
    "kbest_chi2",
    "rfe",
    "rfecv",
    "sfm_l1",
    "sfm_rf",
    "sfm_xgb",
]


def sanitize_filename_component(value: str) -> str:
    """Return a filesystem-safe text component for output filenames."""
    safe_chars = []
    for character in value:
        if character.isalnum() or character in {"-", "_", "."}:
            safe_chars.append(character)
        else:
            safe_chars.append("_")
    return "".join(safe_chars).strip("_") or "dataset"


def build_summary_filename(dataset_labels: list[str]) -> str:
    """Build the summary filename using the dataset label when possible."""
    unique_labels = sorted(set(dataset_labels))

    if len(unique_labels) == 1:
        dataset_label = unique_labels[0]
    else:
        dataset_label = "all_datasets"

    safe_dataset_label = sanitize_filename_component(dataset_label)
    return f"{safe_dataset_label}_complete_model_summary.xlsx"


def parse_arguments() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description=(
            "Rebuild a global model summary from experiment report files already "
            "stored in a results directory. This script does not train models."
        )
    )

    parser.add_argument(
        "--results_dir",
        default=DEFAULT_RESULTS_DIR,
        help=f"Directory containing experiment results. Default: {DEFAULT_RESULTS_DIR}",
    )
    parser.add_argument(
        "--output_file",
        default=DEFAULT_OUTPUT_FILE,
        help=(
            "Output Excel filename. If omitted, the filename is generated from "
            "the dataset subfolder name. If several dataset subfolders are found, "
            "the prefix 'all_datasets' is used."
        ),
    )
    parser.add_argument(
        "--drop_confusion_matrix",
        action="store_true",
        help="Remove the Confusion Matrix column from the final summary.",
    )
    parser.add_argument(
        "--round_digits",
        type=int,
        default=4,
        help="Number of decimal places for numeric metric columns. Default: 4.",
    )

    return parser.parse_args()


def find_model_reports(results_dir: Path) -> list[Path]:
    """Find all model report Excel files generated by the current pipeline."""
    return sorted(results_dir.rglob("*_model_report.xlsx"))


def read_best_parameters(json_path: Path) -> str:
    """Read a best-parameters JSON file and return a compact JSON string."""
    if not json_path.exists():
        return ""

    try:
        with open(json_path, "r", encoding="utf-8") as file:
            json_data = json.load(file)
        return json.dumps(json_data, ensure_ascii=False)
    except Exception as error:
        print(f"[WARN] Could not read best-parameters file {json_path}: {error}")
        return ""


def infer_metadata_from_path(report_path: Path, results_dir: Path) -> dict[str, str]:
    """
    Infer dataset, algorithm, and feature selection method from the results path.

    Expected structure:
        results/<dataset_label>/<algorithm>/<feature_selection_method>/<report.xlsx>
    """
    relative_parts = report_path.relative_to(results_dir).parts

    metadata = {
        "Dataset": "unknown",
        "Algorithm": "unknown",
        "Feature selection method": "unknown",
    }

    if len(relative_parts) >= 4:
        metadata["Dataset"] = relative_parts[0]
        metadata["Algorithm"] = relative_parts[1]
        metadata["Feature selection method"] = relative_parts[2]
        return metadata

    return infer_metadata_from_filename(report_path.name, metadata)


def infer_metadata_from_filename(filename: str, metadata: dict[str, str]) -> dict[str, str]:
    """Infer algorithm and feature selection method from a report filename when path metadata is incomplete."""
    suffix = "_model_report.xlsx"
    if not filename.endswith(suffix):
        return metadata

    prefix = filename[: -len(suffix)]

    for algorithm in KNOWN_ALGORITHMS:
        algorithm_prefix = f"{algorithm}_"
        if prefix.startswith(algorithm_prefix):
            feature_selection_method = prefix[len(algorithm_prefix) :]
            metadata["Algorithm"] = algorithm
            metadata["Feature selection method"] = feature_selection_method
            break

    return metadata


def get_best_parameters_path(report_path: Path, algorithm: str, feature_selection_method: str) -> Path:
    """Build the expected path to the best-parameters JSON file for one experiment."""
    return report_path.parent / f"{algorithm}_{feature_selection_method}_best_parameters.json"


def read_metrics_from_report(report_path: Path) -> dict[str, Any]:
    """Read metrics from one model report Excel file."""
    metrics_df = pd.read_excel(report_path, index_col=0)

    if metrics_df.empty or len(metrics_df.columns) == 0:
        raise ValueError("The report file does not contain metric columns.")

    column_name = metrics_df.columns[0]
    return metrics_df[column_name].to_dict()


def build_summary_row(report_path: Path, results_dir: Path) -> dict[str, Any]:
    """Build one summary row from a model report file."""
    metadata = infer_metadata_from_path(report_path, results_dir)
    metrics = read_metrics_from_report(report_path)

    algorithm = metadata["Algorithm"]
    feature_selection_method = metadata["Feature selection method"]
    best_parameters_path = get_best_parameters_path(
        report_path,
        algorithm,
        feature_selection_method,
    )

    row = {
        "Dataset": metadata["Dataset"],
        "Algorithm": algorithm,
        "Feature selection method": feature_selection_method,
        "Report path": str(report_path),
        **metrics,
        "Best parameters": read_best_parameters(best_parameters_path),
    }

    return row


def round_numeric_columns(summary_df: pd.DataFrame, digits: int) -> pd.DataFrame:
    """Round numeric columns while leaving text/object columns unchanged."""
    summary_df = summary_df.copy()
    numeric_columns = summary_df.select_dtypes(include="number").columns
    summary_df[numeric_columns] = summary_df[numeric_columns].round(digits)
    return summary_df


def rebuild_model_summary(
    results_dir: Path,
    output_file: str | None,
    drop_confusion_matrix: bool,
    round_digits: int,
) -> Path | None:
    """Rebuild and save a complete model summary from existing model reports."""
    if not results_dir.is_dir():
        raise NotADirectoryError(f"Results directory not found: {results_dir}")

    report_paths = find_model_reports(results_dir)

    if not report_paths:
        print(f"[WARN] No model report files were found in: {results_dir}")
        return None

    summary_rows = []

    for report_path in report_paths:
        try:
            summary_rows.append(build_summary_row(report_path, results_dir))
        except Exception as error:
            print(f"[WARN] Could not process {report_path}: {error}")

    if not summary_rows:
        print("[WARN] No valid reports could be processed.")
        return None

    summary_df = pd.DataFrame(summary_rows)

    if drop_confusion_matrix and "Confusion Matrix" in summary_df.columns:
        summary_df = summary_df.drop(columns=["Confusion Matrix"])

    summary_df = round_numeric_columns(summary_df, round_digits)

    if output_file is None:
        dataset_labels = summary_df["Dataset"].astype(str).tolist()
        output_file = build_summary_filename(dataset_labels)

    output_path = Path(output_file)
    if not output_path.is_absolute():
        output_path = results_dir / output_path

    output_path.parent.mkdir(parents=True, exist_ok=True)
    summary_df.to_excel(output_path, index=False)

    print(f"[OK] Processed reports: {len(summary_rows)}")
    print(f"[OK] Summary file saved to: {output_path}")

    return output_path


def main() -> None:
    """Run the summary rebuilding workflow."""
    args = parse_arguments()

    rebuild_model_summary(
        results_dir=Path(args.results_dir),
        output_file=args.output_file,
        drop_confusion_matrix=args.drop_confusion_matrix,
        round_digits=args.round_digits,
    )


if __name__ == "__main__":
    main()
